-- ICT371 QUESTION 3: LIBRARY RETURNS AND OVERDUE FINES
-- Fine = K2 per day late. A return date stops further fine accumulation.

DROP VIEW IF EXISTS v_overdue_loans CASCADE;
DROP TABLE IF EXISTS overdue_summary, loan_audit, loans, books CASCADE;

CREATE TABLE books (
    book_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL
);

CREATE TABLE loans (
    loan_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INTEGER NOT NULL REFERENCES books(book_id),
    borrower_name VARCHAR(120) NOT NULL,
    borrowed_on DATE NOT NULL,
    due_on DATE NOT NULL,
    returned_on DATE,
    fine_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fine_amount >= 0),
    CHECK (due_on >= borrowed_on),
    CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);

CREATE TABLE loan_audit (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id INTEGER NOT NULL REFERENCES loans(loan_id),
    old_returned_on DATE,
    new_returned_on DATE,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE overdue_summary (
    snapshot_date DATE PRIMARY KEY,
    overdue_count BIGINT NOT NULL DEFAULT 0,
    total_fine NUMERIC(14,2) NOT NULL DEFAULT 0
);

-- (b) Fine function. The calculation date is capped at returned_on, if returned.
CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id INTEGER, p_as_of DATE)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
DECLARE
    v_due DATE;
    v_returned DATE;
    v_effective DATE;
BEGIN
    SELECT due_on, returned_on INTO v_due, v_returned
    FROM loans WHERE loan_id = p_loan_id;

    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID: %', p_loan_id; END IF;
    IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date cannot be NULL'; END IF;

    v_effective := LEAST(p_as_of, COALESCE(v_returned, p_as_of));
    RETURN GREATEST(v_effective - v_due, 0) * 2.00;
END;
$$;

-- (d) Audit actual return-date changes.
CREATE OR REPLACE FUNCTION fn_audit_return_change()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.returned_on IS DISTINCT FROM NEW.returned_on THEN
        INSERT INTO loan_audit(loan_id, old_returned_on, new_returned_on)
        VALUES (NEW.loan_id, OLD.returned_on, NEW.returned_on);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_loan_return_audit
AFTER UPDATE OF returned_on ON loans
FOR EACH ROW EXECUTE FUNCTION fn_audit_return_change();

-- (c) Return a loan and store its final fine in one update.
CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id INTEGER, p_returned_on DATE)
LANGUAGE plpgsql AS $$
DECLARE
    v_borrowed DATE;
    v_existing_return DATE;
    v_due DATE;
    v_fine NUMERIC(12,2);
BEGIN
    SELECT borrowed_on, returned_on, due_on
    INTO v_borrowed, v_existing_return, v_due
    FROM loans WHERE loan_id = p_loan_id FOR UPDATE;

    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID: %', p_loan_id; END IF;
    IF v_existing_return IS NOT NULL THEN RAISE EXCEPTION 'Loan % has already been returned', p_loan_id; END IF;
    IF p_returned_on IS NULL OR p_returned_on < v_borrowed THEN
        RAISE EXCEPTION 'Return date must be on or after borrowed date';
    END IF;

    v_fine := GREATEST(p_returned_on - v_due, 0) * 2.00;
    UPDATE loans
    SET returned_on = p_returned_on, fine_amount = v_fine
    WHERE loan_id = p_loan_id;
END;
$$;

