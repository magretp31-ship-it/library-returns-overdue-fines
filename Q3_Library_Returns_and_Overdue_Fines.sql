-- (g) Snapshot: open overdue loans as of p_as_of.
CREATE OR REPLACE PROCEDURE pr_refresh_overdue(p_as_of DATE)
LANGUAGE plpgsql AS $$
BEGIN
    IF p_as_of IS NULL THEN RAISE EXCEPTION 'Snapshot date cannot be NULL'; END IF;

    INSERT INTO overdue_summary(snapshot_date, overdue_count, total_fine)
    SELECT p_as_of, COUNT(*),
           COALESCE(SUM(GREATEST(p_as_of - due_on, 0) * 2.00), 0)
    FROM loans
    WHERE returned_on IS NULL AND due_on < p_as_of
    ON CONFLICT (snapshot_date) DO UPDATE
    SET overdue_count = EXCLUDED.overdue_count,
        total_fine = EXCLUDED.total_fine;
END;
$$;

